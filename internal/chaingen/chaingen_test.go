package chaingen

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

const fixture = `package db

import "context"

type query struct{}
type SelectBuilder struct{ q query }

// Where adds a predicate.
func (b *query) Where(col string, val ...any) *query { return b }

// WhereGroup nests predicates.
func (b *query) WhereGroup(fn func(*query)) *query { return b }

// OrHavingGroup nests having predicates.
func (b *query) OrHavingGroup(fn func(*query)) *query { return b }

// WhereIn takes a subquery named like the receiver.
func (b *query) WhereIn(col string, s *query) *query { return b }

// Err returns the first error.
func (b *query) Err() error { return nil }

// Count is a terminal method.
func (b *query) Count(ctx context.Context) (int64, error) { return 0, nil }

// Exec has no result.
func (b *query) Exec(ctx context.Context) {}

// Clone is skipped.
func (b *query) Clone() *query { return b }

func (b *query) hidden() *query { return b }

func (s *SelectBuilder) Other() {}
`

func writeFixture(t *testing.T, src string) string {
	t.Helper()
	dir := t.TempDir()
	require.NoError(t, os.WriteFile(filepath.Join(dir, "q.go"), []byte(src), 0o600))
	return dir
}

func TestGenerateFromFixture(t *testing.T) {
	out, err := Generate(writeFixture(t, fixture))
	require.NoError(t, err)
	got := string(out)
	assert.Contains(t, got, "Code generated by internal/chaingen")
	assert.Contains(t, got, `"context"`)
	assert.Contains(t, got, "func (s *SelectBuilder) Where(col string, val ...any) *SelectBuilder")
	assert.Contains(t, got, "func (w *WhereClause) Where(")
	assert.Contains(t, got, "func (h *HavingClause) OrHavingGroup(fn func(*HavingClause)) *HavingClause")
	assert.Contains(t, got, "WhereIn(col string, sub *SelectBuilder)", "receiver shadowing must be renamed")
	assert.Contains(t, got, "func (s *SelectBuilder) Count(ctx context.Context) (int64, error)")
	assert.Contains(t, got, "func (s *SelectBuilder) Exec(ctx context.Context) {")
	assert.NotContains(t, got, "Clone")
	assert.NotContains(t, got, "hidden")
	assert.NotContains(t, got, "func (q *Query[T]) Count", "terminal methods are not mirrored on Query[T]")
}

func TestGenerateErrors(t *testing.T) {
	_, err := Generate(writeFixture(t, "package db\nfunc ("))
	require.Error(t, err)

	const noCallback = "package db\ntype query struct{}\nfunc (b *query) Foo(fn func(*query)) *query { return b }\n"
	_, err = Generate(writeFixture(t, noCallback))
	require.ErrorContains(t, err, "no callback type")

	const badParam = "package db\ntype query struct{}\nfunc (b *query) Foo(m map[string]*query) *query { return b }\n"
	_, err = Generate(writeFixture(t, badParam))
	require.ErrorContains(t, err, "unsupported parameter type")
}

func TestGroupOf(t *testing.T) {
	cases := []struct {
		name  string
		chain bool
		want  string
	}{
		{"Err", false, "common"}, {"Prefix", true, "common"}, {"Returning", true, "returning"},
		{"AllRows", true, "allrows"}, {"Get", false, "read"}, {"HavingRaw", true, kHaving},
		{"OrHaving", true, kHaving}, {"WhereIn", true, kWhere}, {"OrWhereIn", true, kWhere},
		{"LeftJoin", true, "join"}, {"OrderBy", true, "orderlimit"}, {"Limit", true, "orderlimit"},
		{"From", true, kSelect},
	}
	for _, c := range cases {
		assert.Equal(t, c.want, groupOf(c.name, c.chain), c.name)
	}
}

func TestImportBlock(t *testing.T) {
	assert.Empty(t, importBlock("func f() {}"))
	assert.Empty(t, importBlock("// uses context. in a comment\n"))
	got := importBlock("var a context.Context\nvar b *sql.DB\nvar c time.Time")
	for _, p := range []string{`"context"`, `"database/sql"`, `"time"`} {
		assert.Contains(t, got, p)
	}
}
